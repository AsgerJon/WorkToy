"""``EZSpaceHook`` integrates field collection and method
auto-generation with the metaclass namespace pipeline.

It runs in two places:

- ``setItemPhase``: rejects definitions of reserved-dunder names
  unless the value is ``@trust``-decorated (in which case the
  value is dropped from the namespace and replaced later).
- ``postCompilePhase``: collects fields, validates orderability if
  requested, sets ``__slots__`` and ``__slot_objects__`` on the
  compiled namespace, and installs the auto-generated dunder
  methods using ``setdefault`` so user-defined overrides are
  preserved."""
