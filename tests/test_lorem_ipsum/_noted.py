from __future__ import annotations

from worktoy.desc import AttriBox
from worktoy.lorem_ipsum import BaseGenerator


class Noted(BaseGenerator):
  """
  The base drops the cached layout through 'clear' whenever the count or
  the first-word flag is assigned, and each subclass replaces 'clear'
  with one dropping its own caches. 'Noted' replaces it with one that
  counts the calls in 'cleared', so the two callbacks can be seen
  firing.
  """

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  NAMESPACE  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  #  Public Variables
  cleared = AttriBox[int](0)

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  DOMAIN SPECIFIC  # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  def clear(self) -> None:
    self.cleared += 1
